// Utility functions
export const getRandomContent = (count: number = 10): Content[] => {
  const allContent = [...mockMovies, ...mockSeries];
  const shuffled = allContent.sort(() => 0.5 - Math.random());
  return shuffled.slice(0, count);
};

export const getFeaturedContent = (): Content[] => {
  return [...mockMovies, ...mockSeries].filter(c => c.isFeatured);
};

export const getContentByGenre = (genre: string): Content[] => {
  return [...mockMovies, ...mockSeries].filter(c => c.genres?.includes(genre));
};

